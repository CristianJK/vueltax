-- Solo datos públicos de referencia. Este esquema no contiene, ni debe contener,
-- tablas de usuarios, viajeros, facturas ni vuelos (ver regla de privacidad en CLAUDE.md).

CREATE TABLE country (
    code     VARCHAR(2) PRIMARY KEY CHECK (code ~ '^[A-Z]{2}$'),
    name     TEXT       NOT NULL,
    currency VARCHAR(3) NOT NULL CHECK (currency ~ '^[A-Z]{3}$'),
    tax_name TEXT       NOT NULL
);

