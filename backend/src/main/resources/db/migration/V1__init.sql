-- Cada versión de un rule set es inmutable: un cambio de reglas es una versión nueva.
CREATE TABLE rule_set (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_code       VARCHAR(2)  NOT NULL REFERENCES country (code),
    version            INTEGER     NOT NULL CHECK (version >= 1),
    content            JSONB       NOT NULL,
    valid_from         DATE        NOT NULL,
    needs_verification BOOLEAN     NOT NULL,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (country_code, version)
);

CREATE TABLE refund_point (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_code  VARCHAR(2)       NOT NULL REFERENCES country (code),
    airport_iata  VARCHAR(3)       NOT NULL CHECK (airport_iata ~ '^[A-Z]{3}$'),
    terminal      TEXT,
    description   TEXT             NOT NULL,
    lat           DOUBLE PRECISION NOT NULL CHECK (lat BETWEEN -90 AND 90),
    lon           DOUBLE PRECISION NOT NULL CHECK (lon BETWEEN -180 AND 180),
    opening_hours TEXT             NOT NULL,
    updated_at    TIMESTAMPTZ      NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX refund_point_natural_key
    ON refund_point (country_code, airport_iata, COALESCE(terminal, ''));

CREATE TABLE exchange_rate (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rate_date  DATE           NOT NULL,
    base       VARCHAR(3)     NOT NULL CHECK (base ~ '^[A-Z]{3}$'),
    quote      VARCHAR(3)     NOT NULL CHECK (quote ~ '^[A-Z]{3}$'),
    rate       NUMERIC(20, 8) NOT NULL CHECK (rate > 0),
    source     TEXT           NOT NULL,
    fetched_at TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT exchange_rate_natural_key UNIQUE (base, rate_date, quote, source)
);
